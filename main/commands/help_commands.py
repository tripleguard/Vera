def execute_help_command(text: str) -> Optional[str]:
    lower = text.lower().strip()

    patterns = [
        r"^(вера[,\s]*)?команды$",
        r"^(вера[,\s]*)?(какие\s+)?(у\s+тебя\s+)?(есть\s+)?команды",
        r"^(вера[,\s]*)?список\s+команд",
        r"^(вера[,\s]*)?что\s+ты\s+умеешь",
        r"^(вера[,\s]*)?твои\s+навыки",
        r"^(вера[,\s]*)?помощь$",
        r"^(вера[,\s]*)?что\s+умеешь",
        r"^(вера[,\s]*)?чем\s+(ты\s+)?можешь\s+помочь",
    ]

    if any(re.search(p, lower) for p in patterns):
        return HELP_TEXT

    return None
